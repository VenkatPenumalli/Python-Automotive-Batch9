#(+)Addition
a = int(input("Enter 1st num :: "))
b = int(input("Enter 2st num :: "))
print("Sum of a + b :: ",a+b)

#(-)Subtraction
print("Difference of a - b :: ",a-b)

#(*)Multiplication
print("Product of a*b :: ",a*b)

#(/)Division
print("Division of a/b :: ",a/b)

#(//)Floor division
print("Floor division of a//b is :: ",a//b)

#(%)Reminder
print("Reminder of a/b", a%b)

#(**)Exponent
print("the exponent of a**b is :: ",a**b)

#Concatination
print("Concatination", a,b)